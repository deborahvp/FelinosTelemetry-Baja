"""Write ``results/`` for a run: summary.json, events.csv and report.md."""

from __future__ import annotations

import csv
import json
import math
from pathlib import Path
from typing import Any


def _clean(obj: Any) -> Any:
    """JSON-safe: NaN/inf → null, numpy scalars → Python."""
    if isinstance(obj, dict):
        return {str(k): _clean(v) for k, v in obj.items()}
    if isinstance(obj, list | tuple):
        return [_clean(v) for v in obj]
    if hasattr(obj, "item") and callable(obj.item):
        obj = obj.item()
    if isinstance(obj, float) and not math.isfinite(obj):
        return None
    return obj


def _fmt(v: Any, digits: int = 2, unit: str = "") -> str:
    if v is None:
        return "—"
    if isinstance(v, float):
        return f"{v:.{digits}f}{(' ' + unit) if unit else ''}"
    return f"{v}{(' ' + unit) if unit else ''}"


def render_markdown(s: dict[str, Any]) -> str:
    run = s["run"]
    u = s["usage"]
    ev = s["events"]
    d = s["durability"]
    lines = [
        f"# Run report — {run['run_id'] or 'unlabeled run'}",
        "",
        f"- Date: {run['date'] or '—'} · Test: {run['test_type']} · Vehicle: {run['vehicle_id'] or '—'}"
        f" · Driver: {run['driver'] or '—'}",
        f"- Duration: {_fmt(s['duration_s'], 1, 's')} · Frame: {s['frame']['platform_convention']}"
        f" convention, {s['frame']['units']}",
        f"- Generated by {s['generated_by']}",
        "",
        "## Vehicle goals",
        "",
    ]
    if s["goals"]:
        lines += [
            "| Goal | Metric | Criterion | Result | Pass |",
            "| --- | --- | --- | --- | --- |",
        ]
        for g in s["goals"]:
            ok = "—" if g["pass"] is None else ("✓" if g["pass"] else "✕")
            note = f" ({g['note']})" if g.get("note") else ""
            lines.append(
                f"| {g['id']} {g['title']} | {g['metric']} | {g['criterion']} | {_fmt(g['value'])}{note} | {ok} |"
            )
    else:
        lines.append("No requirement is verified by this test type.")
    lines += [
        "",
        "## Usage",
        "",
        f"- Active time: {_fmt(u['active_s'], 0, 's')} ({_fmt(u['active_h'], 3, 'h')}) — by GPS {_fmt(u.get('active_gps_s'), 0, 's')}, by IMU vibration where GPS was missing {_fmt(u.get('active_imu_s'), 0, 's')}",
        f"- Distance: {_fmt(u['distance_km'], 3, 'km')} · Mean speed while GPS-active: {_fmt(u['mean_active_speed_kmh'], 1, 'km/h')}",
        "",
        "## Events",
        "",
        "| Impacts | Jumps | Hard braking | Hard cornering |",
        "| --- | --- | --- | --- |",
        f"| {ev['counts']['impact']} | {ev['counts']['jump']} | {ev['counts']['hardBrake']} | {ev['counts']['hardCorner']} |",
        "",
        f"Impact severity bins (g ≥ {ev['impact_bins_g']}): {ev['impact_bins']}. Details in `events.csv`.",
        "",
        "## Durability (VG-02)",
        "",
        f"- Rainflow on `{d['channel']}`: {d['cycles']} cycles",
        f"- Pseudo-damage: {', '.join(f'{k} = {_fmt(v, 3)}' for k, v in d['pseudo_damage'].items())}",
        f"- Per active hour: {', '.join(f'{k} = {_fmt(v, 3)}' for k, v in d['damage_per_active_hour'].items())}",
        f"- Equivalent hours: {_fmt(d['equivalent_hours'], 3)}"
        + (
            ""
            if d["equivalent_hours"] is not None
            else " (set `durability.reference_damage_per_hour`)"
        ),
        f"- Note: {d['note']}.",
        "",
        "## Data quality",
        "",
        "| Sensor | Samples | Rate (Hz) | Gaps | Longest gap (s) |",
        "| --- | --- | --- | --- | --- |",
    ]
    for name, q in s["quality"]["sensors"].items():
        lines.append(
            f"| {name} | {q['samples']} | {q['rate_hz']:.1f} | {q['gaps']} | {q['longest_gap_s']:.2f} |"
        )
    lines += [
        "",
        f"Accelerometer clipping: {s['quality']['accelerometer_clipping_fraction']:.2%} of samples.",
        "",
    ]
    return "\n".join(lines)


def write_results(summary: dict[str, Any], out_dir: Path) -> dict[str, Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    events = summary.get("_events", [])
    public = {k: v for k, v in summary.items() if not k.startswith("_")}
    paths = {
        "summary": out_dir / "summary.json",
        "events": out_dir / "events.csv",
        "report": out_dir / "report.md",
    }
    paths["summary"].write_text(
        json.dumps(_clean(public), indent=2, ensure_ascii=False), encoding="utf-8"
    )
    with paths["events"].open("w", newline="", encoding="utf-8") as fh:
        writer = csv.DictWriter(fh, fieldnames=["type", "t", "peak", "airtime", "bin"])
        writer.writeheader()
        for e in events:
            writer.writerow(_clean(e))
    paths["report"].write_text(render_markdown(_clean(public)), encoding="utf-8")
    return paths
